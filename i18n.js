  /* 표시용 날짜·시간 */
  var MONTH_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  var WD = {
    ko: ['일', '월', '화', '수', '목', '금', '토'],
    en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
    ja: ['日', '月', '火', '水', '木', '金', '土'],
    zh: ['周日', '周一', '周二', '周三', '周四', '周五', '周六'],
    vi: ['CN', 'T2', 'T3', 'T4', 'T5', 'T6', 'T7']
  };

  var listeners = [];
  var lang = 'ko';

  function pad(n) { return (n < 10 ? '0' : '') + n; }

  function detect() {
    var saved = null;
    try { saved = localStorage.getItem(LANG_KEY); } catch (e) {}
    if (saved && DICT[saved]) return saved;
    var nav = '';
    try { nav = String((navigator.languages && navigator.languages[0]) || navigator.language || '').toLowerCase(); } catch (e) {}
    if (nav.indexOf('vi') === 0) return 'vi';
    if (nav.indexOf('ja') === 0) return 'ja';
    if (nav.indexOf('zh') === 0) return 'zh';
    if (nav.indexOf('en') === 0) return 'en';
    if (nav.indexOf('ko') === 0) return 'ko';
    return 'ko';
  }

  function t(key, vars) {
    var table = DICT[lang] || DICT.ko;
    var out = table[key];
    if (out == null) out = DICT.ko[key];
    if (out == null) return key;
    if (!vars) return out;
    return out.replace(/\{(\w+)\}/g, function (m, name) {
      return vars[name] == null ? m : String(vars[name]);
    });
  }

  function isEn() { return lang === 'en'; }

  /* '11. 25.' 같은 경기 날짜 표기 → 언어별 */
  function matchDate(str) {
    var m = /^\s*(\d{1,2})\.\s*(\d{1,2})\.\s*$/.exec(str || '');
    if (!m) return str || '';
    var mo = Number(m[1]);
    var d = Number(m[2]);
    if (lang === 'en') return MONTH_EN[mo - 1] + ' ' + d;
    if (lang === 'ja') return mo + '月' + d + '日';
    if (lang === 'zh') return mo + '月' + d + '日';
    if (lang === 'vi') return d + '/' + mo;
    return mo + '. ' + d + '.';
  }

  /* 요일 이름 */
  function weekday(date) {
    var list = WD[lang] || WD.ko;
    return list[date.getDay()];
  }

  /* 2026.11.27 (금) / Fri, Nov 27, 2026 / 2026年11月27日(金) */
  function feedDate(date) {
    var y = date.getFullYear();
    var mo = date.getMonth() + 1;
    var d = date.getDate();
    if (lang === 'en') return weekday(date) + ', ' + MONTH_EN[mo - 1] + ' ' + d + ', ' + y;
    if (lang === 'ja') return y + '年' + mo + '月' + d + '日(' + weekday(date) + ')';
    if (lang === 'zh') return y + '年' + mo + '月' + d + '日 (' + weekday(date) + ')';
    if (lang === 'vi') return d + '/' + mo + '/' + y + ' (' + weekday(date) + ')';
    return y + '.' + pad(mo) + '.' + pad(d) + ' (' + weekday(date) + ')';
  }

  /* 2026.11.26 17:07 / Nov 26, 2026 17:07 / 2026.11.26 17:07 */
  function stamp(date) {
    if (!date || isNaN(date.getTime())) return '';
    var y = date.getFullYear();
    var mo = date.getMonth() + 1;
    var d = date.getDate();
    var hm = pad(date.getHours()) + ':' + pad(date.getMinutes());
    if (lang === 'en') return MONTH_EN[mo - 1] + ' ' + d + ', ' + y + ' ' + hm;
    if (lang === 'ja') return y + '.' + pad(mo) + '.' + pad(d) + ' ' + hm;
    if (lang === 'zh') return y + '年' + mo + '月' + d + '日 ' + hm;
    if (lang === 'vi') return d + '/' + mo + '/' + y + ' ' + hm;
    return y + '.' + pad(mo) + '.' + pad(d) + ' ' + hm;
  }

  function clock(date) {
    if (!date || isNaN(date.getTime())) return '';
    return pad(date.getHours()) + ':' + pad(date.getMinutes());
  }

  /* 'YYYY-MM-DD' 또는 ISO → 짧은 날짜 */
  function shortDate(value) {
    var date = value instanceof Date ? value : new Date(value);
    if (isNaN(date.getTime())) return '';
    var mo = date.getMonth() + 1;
    var d = date.getDate();
    if (lang === 'en') return MONTH_EN[mo - 1] + ' ' + d;
    if (lang === 'ja') return mo + '月' + d + '日';
    if (lang === 'zh') return mo + '月' + d + '日';
    if (lang === 'vi') return d + '/' + mo;
    return mo + '. ' + d + '.';
  }

  /* 캘린더 달 이름: 11월, 2026 / November, 2026 / 2026年11月 / Tháng 11, 2026 */
  var MONTH_EN_FULL = ['January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'];
  function monthLabel(date) {
    var y = date.getFullYear();
    var mo = date.getMonth() + 1;
    if (lang === 'en') return MONTH_EN_FULL[mo - 1] + ', ' + y;
    if (lang === 'ja' || lang === 'zh') return y + '年' + mo + '月';
    if (lang === 'vi') return 'Tháng ' + mo + ', ' + y;
    return mo + '월, ' + y;
  }
  function monthShort(date) {
    var mo = date.getMonth() + 1;
    if (lang === 'en') return MONTH_EN_FULL[mo - 1];
    if (lang === 'ja' || lang === 'zh') return mo + '月';
    if (lang === 'vi') return 'tháng ' + mo;
    return mo + '월';
  }
  /* 11월 29일 (일) / Sun, Nov 29 / 11月29日(日) / 29/11 (CN) */
  function dayLabel(date) {
    var mo = date.getMonth() + 1;
    var d = date.getDate();
    if (lang === 'en') return WD.en[date.getDay()] + ', ' + MONTH_EN[mo - 1] + ' ' + d;
    if (lang === 'ja') return mo + '月' + d + '日(' + WD.ja[date.getDay()] + ')';
    if (lang === 'zh') return mo + '月' + d + '日 (' + WD.zh[date.getDay()] + ')';
    if (lang === 'vi') return d + '/' + mo + ' (' + WD.vi[date.getDay()] + ')';
    return mo + '월 ' + d + '일 (' + WD.ko[date.getDay()] + ')';
  }
  /* 캘린더 요일 머리글 */
  function wdShort() {
    var list = WD[lang] || WD.ko;
    if (lang === 'zh') return ['日', '一', '二', '三', '四', '五', '六'];
    return list;
  }

  function setLang(code, opts) {
    if (!DICT[code]) code = 'ko';
    lang = code;
    try { localStorage.setItem(LANG_KEY, code); } catch (e) {}
    var meta = LANGS.filter(function (l) { return l.code === code; })[0];
    document.documentElement.setAttribute('lang', meta ? meta.htmlLang : 'ko');
    document.title = t('app.title');
    var desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', t('app.desc'));
    if (!opts || opts.silent !== true) {
      listeners.forEach(function (fn) { try { fn(code); } catch (e) {} });
    }
  }

  function onChange(fn) { listeners.push(fn); }

